"""Branded PDF reports (FR-17), drawn directly with ReportLab so the browser can download them in one click."""
import io
import math
from datetime import datetime
from pathlib import Path

from reportlab.lib.colors import HexColor, white
from reportlab.lib.pagesizes import A4
from reportlab.lib.utils import ImageReader
from reportlab.pdfgen import canvas

from .pose import ANGLES
from .video import overlay_kind

GREEN, DEEP, RED, CREAM, PAPER, INK, MUTED = (HexColor(c) for c in
                                              ("#0f5c3a", "#062a1b", "#c8102e", "#f3e9d2", "#f6f0e2", "#0b1a12", "#6b7a70"))
OK_BG, OK_FG, LOW_BG, LOW_FG, NO_BG = (HexColor(c) for c in ("#d9efe1", "#0f7a45", "#fbe7c6", "#92400e", "#efe9da"))
W, H = A4
M = 36  # page margin (pt)


class Report:
    def __init__(self, title: str, a):
        self.buf = io.BytesIO()
        self.c = canvas.Canvas(self.buf, pagesize=A4)
        self.c.setTitle(f"SmartCricket AI {title}")
        self.c.setAuthor("SmartCricket AI")
        self.title, self.a = title, a
        self.page_no = 0
        self.new_page()

    # ------------------------------------------------------------ page furniture
    def new_page(self):
        if self.page_no:
            self.footer()
            self.c.showPage()
        self.page_no += 1
        c = self.c
        c.setFillColor(DEEP)
        c.rect(0, H - 92, W, 92, stroke=0, fill=1)
        c.setFillColor(RED)
        c.rect(0, H - 96, W, 4, stroke=0, fill=1)
        self.ball(M + 20, H - 46, 19)
        c.setFillColor(white)
        c.setFont("Helvetica-Bold", 19)
        c.drawString(M + 50, H - 46, "SMARTCRICKET AI")
        c.setFillColor(CREAM)
        c.setFont("Helvetica", 8)
        c.drawString(M + 51, H - 60, "BATTING ANALYSIS & COACHING")
        c.setFillColor(white)
        c.setFont("Helvetica-Bold", 16)
        c.drawRightString(W - M, H - 44, self.title.upper())
        c.setFillColor(CREAM)
        c.setFont("Helvetica", 9)
        c.drawRightString(W - M, H - 59, f"{self.a.created_at:%d %b %Y, %H:%M}")
        self.y = H - 120

    def footer(self):
        c = self.c
        c.setStrokeColor(HexColor("#e2dccd"))
        c.line(M, 40, W - M, 40)
        c.setFillColor(MUTED)
        c.setFont("Helvetica", 8)
        c.drawString(M, 27, f"Generated by SmartCricket AI on {datetime.now():%d %b %Y at %H:%M}")
        c.drawRightString(W - M, 27, f"M.E. CSE final-year project · page {self.page_no}")

    def finish(self) -> bytes:
        self.footer()
        self.c.save()
        return self.buf.getvalue()

    def need(self, h):
        if self.y - h < 56:
            self.new_page()

    def ball(self, x, y, r):
        c = self.c
        c.setFillColor(HexColor("#6a0614"))
        c.circle(x + 1, y - 1, r, stroke=0, fill=1)
        c.setFillColor(RED)
        c.circle(x, y, r, stroke=0, fill=1)
        c.setStrokeColor(CREAM)
        c.setLineWidth(r * .055)
        for dx in (-r * .1, r * .12):
            p = c.beginPath()
            p.moveTo(x + dx, y + r * .95)
            p.curveTo(x + dx - r * .38, y + r * .3, x + dx - r * .38, y - r * .3, x + dx, y - r * .95)
            c.drawPath(p, stroke=1, fill=0)
        c.setFillColor(white)
        c.setFillAlpha(.28)
        c.ellipse(x - r * .7, y + r * .25, x - r * .1, y + r * .65, stroke=0, fill=1)
        c.setFillAlpha(1)

    # ------------------------------------------------------------ building blocks
    def heading(self, text):
        self.need(40)
        c = self.c
        c.setFillColor(INK)
        c.setFont("Helvetica-Bold", 13)
        c.drawString(M, self.y, text.upper())
        c.setFillColor(RED)
        c.roundRect(M, self.y - 8, 34, 3, 1.5, stroke=0, fill=1)
        self.y -= 22

    def meta(self, cells):
        n, gap = len(cells), 8
        w = (W - 2 * M - gap * (n - 1)) / n
        for i, (k, v) in enumerate(cells):
            x = M + i * (w + gap)
            self.c.setFillColor(PAPER)
            self.c.roundRect(x, self.y - 38, w, 38, 7, stroke=0, fill=1)
            self.c.setFillColor(MUTED)
            self.c.setFont("Helvetica-Bold", 7)
            self.c.drawString(x + 9, self.y - 14, k.upper())
            self.c.setFillColor(INK)
            self.c.setFont("Helvetica-Bold", 10)
            self.c.drawString(x + 9, self.y - 29, _fit(str(v), "Helvetica-Bold", 10, w - 18))
        self.y -= 52

    def photo_and_kpis(self, img_path: Path | None, kpis):
        box_h, kpi_w, gap = 290, 150, 12
        img_w = W - 2 * M - kpi_w - gap
        self.need(box_h + 10)
        c, top = self.c, self.y
        c.setFillColor(HexColor("#04170e"))
        c.roundRect(M, top - box_h, img_w, box_h, 9, stroke=0, fill=1)
        if img_path and Path(img_path).exists():
            img = ImageReader(str(img_path))
            iw, ih = img.getSize()
            s = min((img_w - 8) / iw, (box_h - 8) / ih)
            dw, dh = iw * s, ih * s
            c.drawImage(img, M + (img_w - dw) / 2, top - box_h + (box_h - dh) / 2, dw, dh)
        kh = (box_h - gap * (len(kpis) - 1)) / len(kpis)
        for i, (label, value, unit, note, red) in enumerate(kpis):
            x, y = M + img_w + gap, top - (i + 1) * kh - i * gap
            c.setStrokeColor(HexColor("#e2dccd"))
            c.setFillColor(white)
            c.roundRect(x, y, kpi_w, kh, 8, stroke=1, fill=1)
            c.setFillColor(MUTED)
            c.setFont("Helvetica-Bold", 6.8)
            c.drawString(x + 10, y + kh - 15, label.upper())
            size = 22 if len(value) < 9 else 13
            c.setFillColor(RED if red else GREEN)
            c.setFont("Helvetica-Bold", size)
            c.drawString(x + 10, y + kh / 2 - size / 3 - 2, _fit(value, "Helvetica-Bold", size, kpi_w - 20))
            if unit:
                c.setFillColor(MUTED)
                c.setFont("Helvetica", 9)
                c.drawString(x + 12 + c.stringWidth(value, "Helvetica-Bold", size), y + kh / 2 - size / 3 - 2, unit)
            if note:
                c.setFillColor(MUTED)
                c.setFont("Helvetica", 7.5)
                c.drawString(x + 10, y + 8, note)
        self.y = top - box_h - 22

    def table(self, header, rows, widths, pill_col=None, bar_col=None):
        c, row_h = self.c, 20
        total = W - 2 * M
        xs = [M]
        for w in widths[:-1]:
            xs.append(xs[-1] + w * total)

        def draw_header():
            c.setFillColor(DEEP)
            c.roundRect(M, self.y - row_h, total, row_h, 6, stroke=0, fill=1)
            c.setFillColor(CREAM)
            c.setFont("Helvetica-Bold", 7.5)
            for x, h in zip(xs, header):
                c.drawString(x + 9, self.y - 13, h.upper())
            self.y -= row_h

        self.need(row_h * 2)
        draw_header()
        for r in rows:
            if self.y - row_h < 56:
                self.new_page()
                draw_header()
            for i, (x, v) in enumerate(zip(xs, r)):
                if i == pill_col:
                    text, kind = v
                    bg, fg = {"ok": (OK_BG, OK_FG), "low": (LOW_BG, LOW_FG)}.get(kind, (NO_BG, MUTED))
                    tw = c.stringWidth(text, "Helvetica-Bold", 7.5) + 14
                    c.setFillColor(bg)
                    c.roundRect(x + 7, self.y - 15, tw, 12, 6, stroke=0, fill=1)
                    c.setFillColor(fg)
                    c.setFont("Helvetica-Bold", 7.5)
                    c.drawString(x + 14, self.y - 11.5, text)
                elif i == bar_col:
                    label, frac = v
                    c.setFillColor(INK)
                    c.setFont("Helvetica", 9)
                    c.drawString(x + 9, self.y - 13, label)
                    bx = x + 9 + c.stringWidth(label, "Helvetica", 9) + 6
                    c.setFillColor(NO_BG)
                    c.roundRect(bx, self.y - 12, 60, 5, 2.5, stroke=0, fill=1)
                    c.setFillColor(HexColor("#1f9d55"))
                    c.roundRect(bx, self.y - 12, max(2, 60 * max(0, min(1, frac))), 5, 2.5, stroke=0, fill=1)
                else:
                    c.setFillColor(INK)
                    c.setFont("Helvetica-Bold" if i == 1 else "Helvetica", 9)
                    c.drawString(x + 9, self.y - 13, str(v))
            c.setStrokeColor(HexColor("#ebe5d6"))
            c.line(M, self.y - row_h, M + total, self.y - row_h)
            self.y -= row_h
        self.y -= 16

    def paragraph(self, text, size=8.5, color=MUTED, italic=True, box=False):
        c = self.c
        font = "Helvetica-Oblique" if italic else "Helvetica"
        lines = _wrap(text, font, size, W - 2 * M - (24 if box else 0))
        h = len(lines) * (size + 3.5) + (18 if box else 0)
        self.need(h)
        if box:
            c.setFillColor(PAPER)
            c.roundRect(M, self.y - h, W - 2 * M, h, 7, stroke=0, fill=1)
            c.setFillColor(GREEN)
            c.rect(M, self.y - h, 3.5, h, stroke=0, fill=1)
        c.setFillColor(color)
        c.setFont(font, size)
        y = self.y - (12 if box else 2) - size * .6
        for ln in lines:
            c.drawString(M + (14 if box else 0), y, ln)
            y -= size + 3.5
        self.y -= h + 10


def _fit(text, font, size, width):
    from reportlab.pdfbase.pdfmetrics import stringWidth
    if stringWidth(text, font, size) <= width:
        return text
    while text and stringWidth(text + "…", font, size) > width:
        text = text[:-1]
    return text + "…"


def _wrap(text, font, size, width):
    from reportlab.pdfbase.pdfmetrics import stringWidth
    words, lines, cur = text.split(), [], ""
    for w in words:
        t = (cur + " " + w).strip()
        if stringWidth(t, font, size) <= width:
            cur = t
        else:
            lines.append(cur)
            cur = w
    if cur:
        lines.append(cur)
    return lines


# ---------------------------------------------------------------- the two reports
def photo_pdf(a) -> bytes:
    s = a.summary or {}
    r = Report("Posture report", a)
    visible, total = s.get("visible", 0), s.get("total", 33)
    r.meta([("Date", f"{a.created_at:%d %b %Y}"), ("Time", f"{a.created_at:%H:%M}"), ("Points visible", f"{visible} of {total}")])
    order = sorted((a.angles or {}).items(), key=lambda kv: list(ANGLES).index(kv[0]) if kv[0] in ANGLES else 99)
    measured = sum(1 for _, v in order if v["deg"] is not None)
    tilt = s.get("shoulder_line_deg")
    r.photo_and_kpis(a.output_path, [
        ("Body points visible", str(visible), f"/ {total}", "", False),
        ("Angles measured", str(measured), "/ 8", "", True),
        ("Shoulder tilt", "-" if tilt is None else f"{tilt}°", "", "from horizontal", False),
        ("Analysis time", str(a.latency_ms or 0), "ms", "", False),
    ])
    r.heading("Joint angles")
    rows = []
    for n, v in order:
        ok = v["deg"] is not None
        status = ("✓ measured", "ok") if ok and v["visibility"] >= .65 else ("less certain", "low") if ok else ("not visible", "no")
        rows.append([n.replace("_", " ").title(), f"{v['deg']}°" if ok else "–",
                     (f"{v['visibility']:.2f}", v["visibility"]), status])
    r.table(["Joint", "Angle", "Visibility", "Status"], rows, [.32, .18, .27, .23], pill_col=3, bar_col=2)
    notes = s.get("notes", [])
    if notes:
        r.paragraph("Notes: " + " ".join(notes), size=8.8, color=INK, italic=False, box=True)
    r.paragraph('Angles are 2D estimates from one camera view. "Left" and "right" are the batter\'s own sides. '
                "They describe posture; they are not a judgement of correct or incorrect technique and not medical advice.")
    return r.finish()


def video_pdf(a) -> bytes:
    s = a.summary or {}
    d = Path(a.output_path)
    key = s.get("key_frame", 0)
    kind = overlay_kind(s) or "frame"
    att = s.get("attention") or []
    movement = not a.shot
    r = Report("Movement analysis report" if movement else "Shot analysis report", a)
    r.meta([("Date", f"{a.created_at:%d %b %Y}"), ("Time", f"{a.created_at:%H:%M}"), ("Model", s.get("model_label", a.model))])
    if movement:
        ranges = s.get("joint_ranges") or {}
        knees = [v["min"] for j, v in ranges.items() if j.endswith("knee")]
        r.photo_and_kpis(d / f"{kind}_{key:02d}.jpg", [
            ("Body tracked", str(s.get("tracked_frames", 0)), f"/ {s.get('frames', 0)} frames", "4 or more angles measured", False),
            ("Most movement", "Frame " + str(key + 1), "", f"{(att[key] * 100 if att else 0):.1f}% of all movement", True),
            ("Deepest knee bend", f"{min(knees):.1f}" if knees else "-", "°" if knees else "", "more bent knee", False),
            ("Analysis time", str(a.latency_ms or 0), "ms", "", False),
        ])
        r.heading("Joint ranges over the clip")
        names = {j: j.replace("_", " ").title() for j in ranges}
        r.table(["Joint", "Most bent", "Most open", "Range"],
                [[names[j], f"{v['min']:.1f}° (frame {v['min_frame'] + 1})", f"{v['max']:.1f}° (frame {v['max_frame'] + 1})",
                  (f"{v['range']:.1f}°", min(1.0, v["range"] / 90))] for j, v in ranges.items()],
                [.25, .27, .27, .21], bar_col=3)
        r.paragraph("Shot type was not identified: this clip was analysed for body movement only. The shot name, confidence "
                    "and heatmaps are added when the trained shot models are installed.")
    else:
        r.photo_and_kpis(d / f"{kind}_{key:02d}.jpg", [
            ("Predicted shot", a.shot or "-", "", "", True),
            ("Calibrated confidence", f"{(a.confidence or 0) * 100:.1f}", "%", "Uncertain" if a.uncertain else "Confident", False),
            ("Key frame", str(key + 1), f"/ {s.get('frames', 0)}", f"{(att[key] * 100 if att else 0):.1f}% of attention", False),
            ("Analysis time", str(a.latency_ms or 0), "ms", "", False),
        ])
        r.heading("Top 3 shots")
        r.table(["#", "Shot", "Probability"],
                [[str(i + 1), t["shot"], (f"{t['prob'] * 100:.1f}%", t["prob"])] for i, t in enumerate(a.top3 or [])],
                [.1, .5, .4], bar_col=2)
    frames = s.get("frames", 0)
    if frames:
        r.heading("All frames")
        cols, gap = 5, 6
        fw = (W - 2 * M - gap * (cols - 1)) / cols
        fh = fw * 9 / 16
        for t in range(frames):
            if t % cols == 0:
                r.need(fh + gap)
            col = t % cols
            x, y = M + col * (fw + gap), r.y - fh
            p = d / f"{kind}_{t:02d}.jpg"
            r.c.setFillColor(HexColor("#04170e"))
            r.c.roundRect(x, y, fw, fh, 4, stroke=0, fill=1)
            if p.exists():
                img = ImageReader(str(p))
                iw, ih = img.getSize()
                sc = min(fw / iw, fh / ih)
                r.c.drawImage(img, x + (fw - iw * sc) / 2, y + (fh - ih * sc) / 2, iw * sc, ih * sc)
            if t == key:
                r.c.setStrokeColor(RED)
                r.c.setLineWidth(2)
                r.c.roundRect(x, y, fw, fh, 4, stroke=1, fill=0)
            r.c.setFillColor(DEEP)
            r.c.roundRect(x + 3, y + fh - 13, 16, 10, 5, stroke=0, fill=1)
            r.c.setFillColor(white)
            r.c.setFont("Helvetica-Bold", 6.5)
            r.c.drawCentredString(x + 11, y + fh - 10.5, str(t + 1))
            if col == cols - 1 or t == frames - 1:
                r.y -= fh + gap
        r.y -= 12
    if a.dtw:
        r.heading("Comparison with reference")
        r.paragraph(f"Reference: {a.dtw['reference_label']}. DTW distance {a.dtw['distance']}° per aligned frame (lower is closer).",
                    color=INK, italic=False)
        r.table(["Joint", "Mean difference", "Player minus reference"],
                [[j.replace("_", " ").title(), f"{v['mean_abs_diff']}°", f"{v['mean_diff']:+}°"]
                 for j, v in a.dtw["per_joint"].items() if v], [.4, .3, .3])
    r.paragraph("A heatmap shows where the model looked; it does not prove the model reasoned correctly. Joint angles are 2D "
                "estimates from one camera view and are not a judgement of technique or medical advice.")
    return r.finish()
